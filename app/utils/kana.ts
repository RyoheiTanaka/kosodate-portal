/**
 * かなの正規化 (#128)。
 *
 * `name_kana` はカタカナで格納されているため、ひらがなで打つと部分一致しない。
 * スマホの日本語入力は既定がひらがなで、ひらがなで打つほうがむしろ自然なので、
 * 入力と対象の両方をカタカナに寄せてから比べる。
 *
 * カタカナ側に寄せているのは、`name_kana` がすべてカタカナで、
 * 変換対象が少ないほうが速いため（園名にひらがな表記のものもあるが少数）。
 *
 * 濁点・半濁点は合成済みの1文字として入っており、範囲変換でそのまま対応する
 * （`が`(U+304C) → `ガ`(U+30AC)）。小書き文字も同様に1対1で写る。
 * 長音符（`ー`）はひらがな・カタカナで共通なので変換しない。
 *
 * #120 で Atlas Search に移ればアナライザ側で正規化できるので、この変換は不要になる。
 */

/** ひらがなとカタカナの符号位置の差 */
const KATAKANA_OFFSET = 0x60

/**
 * ひらがなをカタカナに寄せる。カタカナ・漢字・英数字はそのまま返す。
 *
 * 対象は `ぁ`(U+3041) から `ゖ`(U+3096) まで。
 *
 * @example toKatakana('みどりの') // 'ミドリノ'
 */
export const toKatakana = (value: string): string =>
  value.replace(/[ぁ-ゖ]/g, char => String.fromCharCode(char.charCodeAt(0) + KATAKANA_OFFSET))
